/*
 * The boards' "deep" backdrop (Server find, Server unreachable, TV screensaver): the deep-blue water, light rays
 * leaning through it, drifting marine snow, rising bubbles, a few dark fish and the sea floor with swaying weed. It
 * loops as the boards' CSS does; with motion off it holds a still frame.
 */

/** A light ray: its left edge and width (board px) and its animation delay. */
class Ray(val left: Float, val width: Float, val delay: Double)

/** A speck of marine snow: where it starts, its size and opacity, and its fall. */
class Snow(val left: Float, val top: Float, val size: Float, val opacity: Float, val duration: Double, val delay: Double)

/** A bubble: where it starts (from the bottom), its size, and its rise. */
class Bubble(val left: Float, val bottom: Float, val size: Float, val duration: Double, val delay: Double)

/** A fish crossing the screen, facing back the other way when [back]. */
class Fish(val top: Float, val width: Float, val height: Float, val color: Color, val duration: Double, val delay: Double, val back: Boolean)

